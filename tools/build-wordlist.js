// Builds src/renderer/words-data.js — a compact rhyme + syllable dictionary.
// Sources: CMU Pronouncing Dictionary (BSD-style) via cmu-pronouncing-dictionary (ISC)
// and SCOWL word lists via wordlist-english (MIT). Run with: npm run build-words
const fs = require('fs');
const path = require('path');

(async () => {
  const { dictionary } = await import('cmu-pronouncing-dictionary');
  const wl = (n) => require(`wordlist-english/${n}.json`);
  const levels = [
    [1, [...wl('english-words-10'), ...wl('american-words-10')]],
    [2, [...wl('english-words-20'), ...wl('american-words-20')]],
    [3, [...wl('english-words-35'), ...wl('american-words-35')]],
  ];
  const seen = new Map();
  for (const [lvl, words] of levels) for (const w of words) {
    if (!/^[a-z]+$/.test(w)) continue;
    if (!seen.has(w)) seen.set(w, lvl);
  }
  const rhymeKey = (phones) => {
    const p = phones.split(' ');
    let idx = -1;
    for (let i = p.length - 1; i >= 0; i--) if (/1$/.test(p[i])) { idx = i; break; }
    if (idx < 0) for (let i = p.length - 1; i >= 0; i--) if (/2$/.test(p[i])) { idx = i; break; }
    if (idx < 0) for (let i = p.length - 1; i >= 0; i--) if (/\d$/.test(p[i])) { idx = i; break; }
    if (idx < 0) return null;
    return p.slice(idx).map((x) => x.replace(/\d/, '')).join('-');
  };
  const entries = [];
  for (const [w, lvl] of seen) {
    const ph = dictionary[w];
    if (!ph) continue;
    const syl = (ph.match(/\d/g) || []).length;
    const key = rhymeKey(ph);
    if (!key) continue;
    entries.push([w, lvl, syl, key]);
  }
  // Encode as "word,level,syllables,key;..." to keep the file small.
  const out = entries.map((e) => e.join(',')).join(';');
  const js = `// Generated by tools/build-wordlist.js — do not edit by hand.\n// Pronunciations: CMU Pronouncing Dictionary. Word lists: SCOWL.\nwindow.WORD_DATA = ${JSON.stringify(out)};\n`;
  fs.writeFileSync(path.join(__dirname, '..', 'src', 'renderer', 'words-data.js'), js);
  console.log('words:', entries.length, 'bytes:', js.length);
})();
